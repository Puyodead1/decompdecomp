#!/usr/bin/env python3
"""Build this decompilation and check the result against your own copy of the program, byte for byte.

    python build.py              build every decompiled function into a copy of the program, compare
    python build.py check NAME   check one function's C (src/<source file>/NAME.c) against the original
    python build.py relink       only link a new program from the C (build/<program>; --move: its data moves too)
    python build.py status       how many functions are C so far

Each function with C is compiled with Slackware 8.0's GCC 2.95.3 (as it was where it lies: at its address modulo 16,
which GCC 2.95's loop padding depends on), linked alone at its address with the toolchain's own ld (its constants
where the program keeps them, the program's other symbols at their addresses: build.json), and its code put in place
in build/program, a copy of your program. Generated by decompdecomp (https://github.com/n-delic/decompdecomp), which
provides the pinned tools.
"""

from __future__ import annotations

import dataclasses
import hashlib
import json
import re
import shutil
import sys
from io import BytesIO
from pathlib import Path

ROOT = Path(__file__).resolve().parent
B = json.loads((ROOT / "build.json").read_text(encoding="utf-8"))
FUNCTIONS = {f["name"]: f["vram"] for f in B["functions"]}  # (the program's functions, where it has them)
ALIGN = 16  # (GCC 2.95 aligns an object's .text, its loops' .p2align 4: a function sits at its address modulo 16)

try:
    from elftools.elf.elffile import ELFFile

    from decompnet import toolchains
    from decompnet.arch.x86_link import load_widths
    from decompnet.compiler import compile_source, run_in
    from decompnet.project import compiler_config
except ImportError:
    sys.exit("This build uses decompdecomp's pinned tools: install decompdecomp first (https://github.com/n-delic/decompdecomp).")


def fail(msg: str) -> None:
    sys.exit(f"error: {msg}")


def original() -> bytes:
    base = ROOT / B["image"]
    if not base.exists():
        fail(f"put your own copy of the program here as {B['image']} (see README.md)")
    data = base.read_bytes()
    if hashlib.sha1(data).hexdigest() != B["sha1"]:
        fail(f"{B['image']} isn't the version this project decompiles (its SHA-1 differs)")
    return data


def source_of(fn: dict) -> Path | None:
    path = ROOT / (fn.get("c") or "")
    if fn.get("c") and path.exists():
        return path
    found = sorted((ROOT / "src").glob(f"*/{fn['name']}.c"))
    return found[0] if found else None


def config(fn: dict, work: Path, placed: bool = True):
    """How the function is compiled: `placed`, at its address modulo 16 (the matching build); else as written (the
    relinked program, where the code moves)."""
    cfg = compiler_config(work, {"compiler": {"toolchain": toolchain(fn), "flags": fn.get("flags") or ["-O2"]}})
    pad = fn["vram"] % ALIGN
    # (or where the code before it in its file put it, after code that grew as gas relaxed it: build.json says)
    space = fn.get("prelude") or (f'__asm__(".text\\n\\t.space {pad}\\n");\n' if pad else "")
    return dataclasses.replace(cfg, prelude=cfg.prelude + (space if placed else ""),
                               include_dirs=(*cfg.include_dirs, str(ROOT / "include")))


def own_data(elf, data: bytes, fn: dict, pad: int) -> tuple[dict[str, int], list[tuple[int, str, int]]]:
    """Where the function's own constants (strings, jump tables, floats) go: where the original's code points at
    them. Each word the object relocates against one of its own sections holds, in the original, the address the
    game keeps that constant at, so the section's place is that address less the offset into it.

    A section whose constants the game keeps apart (GCC merges a file's equal strings: a function's "%s\n" is the
    copy an earlier function of the game's file has) can't go to one place: its words are the game's addresses, each
    checked to hold the same bytes as the object's constant (scattered: (offset in .text, section, offset in it)),
    as the judge checks them. 105 functions of a Linux game's 1,588 were left as the program's bytes for that."""
    from elftools.elf.relocation import RelocationSection

    t = B["text"]
    start = t["offset"] + fn["vram"] - pad - t["vram"]
    text_idx = next(i for i, s in enumerate(elf.iter_sections()) if s.name == ".text")
    found: dict[str, set[int]] = {}
    refs: list[tuple[int, str, int]] = []
    for rsec in elf.iter_sections():
        if not isinstance(rsec, RelocationSection) or rsec["sh_info"] != text_idx:
            continue
        symtab = elf.get_section(rsec["sh_link"])
        for rel in rsec.iter_relocations():
            sym = symtab.get_symbol(rel["r_info_sym"])
            if rel["r_info_type"] != 1 or sym["st_info"]["type"] not in ("STT_SECTION", "STT_OBJECT") \
                    or not isinstance(sym["st_shndx"], int) or sym["st_shndx"] == text_idx:
                continue
            at = rel["r_offset"]
            if not pad <= at < pad + fn["size"]:
                continue
            section = elf.get_section(sym["st_shndx"]).name
            obj_text = elf.get_section(text_idx).data()
            addend = int.from_bytes(obj_text[at:at + 4], "little") + (sym["st_value"] if sym["st_info"]["type"] ==
                                                                       "STT_OBJECT" else 0)
            found.setdefault(section, set()).add(int.from_bytes(data[start + at:start + at + 4], "little") - addend)
            refs.append((at, section, addend))
    placed = {section: next(iter(bases)) for section, bases in found.items() if len(bases) == 1}
    scattered = [(at, section, addend) for at, section, addend in refs if section not in placed]
    if scattered:
        game = ELFFile(BytesIO(data))
        obj_text = elf.get_section(text_idx).data()
        where_of = {(section, addend): int.from_bytes(data[start + at:start + at + 4], "little")
                    for at, section, addend in refs}
        later = sorted(set(where_of.values()))
        widths: dict[tuple[str, int], int | None] = {}
        loads = load_widths(obj_text)
        for at, section, addend in refs:  # (what the code only loads counts as far as it loads it, as the judge's)
            key, width = (section, addend), loads.get(at)
            widths[key] = width if key not in widths else (
                max(widths[key], width) if widths[key] and width else None)
        for at, section, addend in scattered:
            sec = elf.get_section_by_name(section)
            if sec["sh_type"] == "SHT_NOBITS":
                continue
            ends = sorted({a for _, s2, a in refs if s2 == section and a > addend} | {sec["sh_size"]})
            want = bytearray(sec.data()[addend:ends[0]])
            where = where_of[(section, addend)]
            # the addresses it holds itself (a switch's jump table: words into the function's code), relocated
            for off, target, value in _relocations(elf, section):
                if not addend <= off <= addend + len(want) - 4:
                    continue
                if target == text_idx:
                    word = fn["vram"] - pad + value
                elif (elf.get_section(target).name, value) in where_of:
                    word = where_of[(elf.get_section(target).name, value)]
                else:
                    fail(f"{fn['name']}'s {section} isn't laid out like the program's, and it holds addresses itself")
                want[off - addend:off - addend + 4] = (word & 0xFFFFFFFF).to_bytes(4, "little")
            width = widths.get((section, addend))
            want = bytes(want[:width] if width else want[:significant(bytes(want), where, [w for w in later if w > where])])
            if file_bytes(game, data, where, len(want)) != want:
                fail(f"{fn['name']}'s {section}+0x{addend:X} isn't the program's data at 0x{where:X}")
    return placed, scattered


def _relocations(elf, section: str) -> list[tuple[int, int, int]]:
    """The absolute addresses a section of the object holds: (offset in it, the section they point into, the offset
    there)."""
    from elftools.elf.relocation import RelocationSection

    out = []
    for rsec in elf.iter_sections():
        if isinstance(rsec, RelocationSection) and elf.get_section(rsec["sh_info"]).name == section:
            symtab, own = elf.get_section(rsec["sh_link"]), elf.get_section_by_name(section).data()
            for rel in rsec.iter_relocations():
                sym = symtab.get_symbol(rel["r_info_sym"])
                if rel["r_info_type"] != 1 or not isinstance(sym["st_shndx"], int):
                    fail(f"{section} holds an address this build can't place")
                value = int.from_bytes(own[rel["r_offset"]:rel["r_offset"] + 4], "little")
                out.append((rel["r_offset"], sym["st_shndx"],
                            value + (sym["st_value"] if sym["st_info"]["type"] != "STT_SECTION" else 0)))
    return out


def significant(mine: bytes, where: int, later: list[int]) -> int:
    """How much of a constant must be the program's, as the judge counts it (decompdecomp's rom/link.py): not the
    zeros the compiler pads it with up to an alignment, where the program keeps its next constant already, after
    a string's terminator or after a number's last word ("    barmd NO tex\\n" padded to 32 bytes in the object, the next string right after it in
    the program)."""
    k = len(mine.rstrip(b"\0"))
    if k + 1 >= len(mine):
        return len(mine)
    nxt = min((w for w in later if w >= where + k + 1), default=None)
    if nxt is not None and nxt < where + len(mine):
        return nxt - where
    # (a string is plain ASCII here: the judge also counts bytes from 0x80 as text, but knows how much of a float
    # the code loads; this doesn't, and 0.6602f is 97 ff 28 3f)
    if k and all(32 <= c < 127 or c in (9, 10, 13, 27) for c in mine[:k]):
        return k + 1
    # a number (a float the code loads, padded to the double after it): its words up to the last that isn't zero
    return min(len(mine), max(4, -(-k // 4) * 4))


def file_bytes(game, data: bytes, address: int, size: int) -> bytes | None:
    """The program's bytes at an address, from the section that holds it."""
    for section in game.iter_sections():
        lo = section["sh_addr"]
        if section["sh_type"] != "SHT_NOBITS" and lo and lo <= address and address + size <= lo + section["sh_size"]:
            at = section["sh_offset"] + address - lo
            return data[at:at + size]
    return None


def build_function(fn: dict, data: bytes) -> bytes:
    """The function's code as its C compiles and links at its address."""
    src = source_of(fn)
    work = ROOT / "build" / "obj"
    work.mkdir(parents=True, exist_ok=True)
    cfg = config(fn, work)
    res = compile_source(cfg, "", src.read_text(encoding="utf-8"), trusted=True)
    if not res.ok:
        fail(f"{src.relative_to(ROOT)} doesn't compile:\n{res.log[-3000:]}")
    obj = work / f"{fn['name']}.o"
    obj.write_bytes(unaligned_text(res.obj))
    elf = ELFFile(BytesIO(res.obj))
    # where the function sits in its .text: its offset modulo 16, after the code its prelude puts before it
    pad = next(s["st_value"] for s in elf.get_section_by_name(".symtab").iter_symbols() if s.name == fn["name"])
    placed, scattered = own_data(elf, data, fn, pad)
    own = "".join(f"  .own{i} 0x{addr:X} : {{ {obj.name}({section}) }}\n"
                  for i, (section, addr) in enumerate(placed.items()))
    # every name but the function's own at the program's address, those the C defines too: a C file that defines the
    # functions and globals before it (GCC 4.3 inlines them, as the game's file did) calls and reads the program's,
    # as the judge links it (a static the C defines is local to its object: the assignment doesn't touch it)
    program = {**B["symbols"], **FUNCTIONS}
    symbols = "".join(f"{name} = 0x{addr:X};\n" for name, addr in program.items() if name != fn["name"])
    (work / f"{fn['name']}.ld").write_text(
        f"SECTIONS {{\n  .text 0x{fn['vram'] - pad:X} : {{ {obj.name}(.text) }}\n{own}"
        f"  .rest 0x70000000 : {{ *(.rodata) *(.data) *(.bss) *(COMMON) }}\n"
        f"  /DISCARD/ : {{ *(.comment) *(.note*) *(.stab*) }}\n}}\n{symbols}", encoding="utf-8")
    tc = toolchains.ensure(toolchain(fn), log=lambda *_: None)
    out = f"{fn['name']}.elf"
    res = run_in(cfg, work, ["/bin/sh", "-c",
                             f'LD_LIBRARY_PATH="{tc}/binutils/usr/lib${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}" exec '
                             f'"{tc}/binutils/usr/bin/ld" -m elf_i386 -e 0 -T {fn["name"]}.ld -o {out} {obj.name}'])
    if res.returncode != 0:
        fail(f"{fn['name']} doesn't link:\n{(res.stdout + res.stderr)[-3000:]}")
    text = bytearray(ELFFile(BytesIO((work / out).read_bytes())).get_section_by_name(".text").data())
    t = B["text"]
    start = t["offset"] + fn["vram"] - pad - t["vram"]
    for at, _, _ in scattered:  # (the game's address of a constant checked to be the object's: own_data)
        text[at:at + 4] = data[start + at:start + at + 4]
    _pic(elf, text, fn["vram"] - pad, program)
    return bytes(text[pad:pad + fn["size"]])


def _pic(elf, text: bytearray, base: int, program: dict) -> None:
    """Code built with -fPIC (glibc's atexit) linked as the program has it: the GOT where the program's is, a
    global's address read from the GOT entry the program's dynamic relocation gives it, a call through the import's
    PLT stub (linked alone, ld would make a GOT of its own)."""
    from elftools.elf.relocation import RelocationSection

    got = B.get("got") or {}
    slots = {name: int(addr, 16) for addr, name in (got.get("slots") or {}).items()}
    obj = elf.get_section_by_name(".text").data()
    ti = next(i for i, s_ in enumerate(elf.iter_sections()) if s_.name == ".text")
    for rs in elf.iter_sections():
        if not isinstance(rs, RelocationSection) or rs["sh_info"] != ti:
            continue
        symtab = elf.get_section(rs["sh_link"])
        for r in rs.iter_relocations():
            kind, at = r["r_info_type"], r["r_offset"]
            if kind not in (3, 4, 10):
                continue
            name = symtab.get_symbol(r["r_info_sym"]).name
            addend = int.from_bytes(obj[at:at + 4], "little", signed=True)
            if kind == 10:  # R_386_GOTPC
                if got.get("base") is None:
                    fail("this code is built with -fPIC, and build.json doesn't say where the program's GOT is: export again")
                value = got["base"] + addend - (base + at)
            elif kind == 3:  # R_386_GOT32
                if name not in slots:
                    fail(f"the program's GOT has no entry for {name}")
                value = slots[name] - got["base"] + addend
            else:  # R_386_PLT32
                if name not in program:
                    fail(f"{name} isn't a function the program has")
                value = program[name] + addend - (base + at)
            text[at:at + 4] = (value & 0xFFFFFFFF).to_bytes(4, "little")


def unaligned_text(obj: bytes) -> bytes:
    """The object with its .text aligned to 1, so ld puts it exactly where the script says. The judge takes the
    function's bytes from its symbol and relocates them at its address: one whose file's C defines functions before
    it can sit at another offset modulo 16 in its object than in the game (a 2000s Linux game's 86-byte function
    with no loop, after three others), and ld rounded the 16-aligned .text up to the next 16, 12 bytes off."""
    elf = ELFFile(BytesIO(obj))
    out = bytearray(obj)
    for i, section in enumerate(elf.iter_sections()):
        if section.name == ".text":
            at = elf["e_shoff"] + i * elf["e_shentsize"] + 32  # Elf32_Shdr.sh_addralign
            out[at:at + 4] = (1).to_bytes(4, "little")
    return bytes(out)


def toolchain(fn: dict) -> str:
    return fn.get("toolchain") or B.get("toolchain") or "gcc-2.95.3-linux"


def place(image: bytearray, fn: dict, code: bytes) -> None:
    t = B["text"]
    at = t["offset"] + fn["vram"] - t["vram"]
    image[at:at + fn["size"]] = code.ljust(fn["size"], b"\0")[:fn["size"]]


def build() -> None:
    data = original()
    image = bytearray(data)
    done, wrong = 0, []
    for fn in B["functions"]:
        if source_of(fn) is None:
            continue
        code = build_function(fn, data)
        t = B["text"]
        at = t["offset"] + fn["vram"] - t["vram"]
        if code != data[at:at + fn["size"]]:
            wrong.append(fn["name"])
        place(image, fn, code)
        done += 1
    out = ROOT / B["output"]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(bytes(image))
    out.chmod(0o755)
    if bytes(image) == data:
        print(f"{out.relative_to(ROOT)}: identical to the original ({done} of {len(B['functions'])} functions from C)")
        return
    fail(f"{out.relative_to(ROOT)} differs from the original: " + ", ".join(wrong[:20]) +
         (f" and {len(wrong) - 20} more" if len(wrong) > 20 else ""))


def check(name: str) -> None:
    data = original()
    fn = next((f for f in B["functions"] if f["name"] == name), None)
    if fn is None:
        fail(f"no function named {name} in build.json")
    src = source_of(fn)
    if src is None:
        fail(f"write it first as src/<source file>/{name}.c")
    code = build_function(fn, data)
    t = B["text"]
    at = t["offset"] + fn["vram"] - t["vram"]
    want = data[at:at + fn["size"]]
    if code != want:
        first = next((i for i, (a, b) in enumerate(zip(code, want)) if a != b), min(len(code), len(want)))
        fail(f"{name} differs from the original at +0x{first:X} ({len(code)} bytes, the original's {len(want)})")
    fn["c"] = src.relative_to(ROOT).as_posix()
    (ROOT / "build.json").write_text(json.dumps(B, indent=1), encoding="utf-8")
    print(f"{name}: matches")


# ---------------------------------------------------------------------------------------------------- relinking
# A new program from the C: every function compiled as written (no padding to the place it had: the code moves),
# laid out by ld from CODE_BASE where it may grow, linked with the toolchain's own crt files and the libraries the
# program imports from (stubs made from your copy's import table, the versions it asked for; it runs with the real
# ones). The data isn't C yet: .rodata, .data and .bss stay at their addresses, every word in them that pointed at a
# function now pointing at it where it is, and each function's own statics are the game's (build.json "statics").

SHF_WRITE, SHN_UNDEF, SHN_COMMON = 1, 0, 0xFFF2


def _tool(tc: Path, name: str) -> str:
    return f'LD_LIBRARY_PATH="{tc}/binutils/usr/lib:{tc}/lib${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}" "{tc}/binutils/usr/bin/{name}"'


def _run(cfg, work: Path, command: str, what: str) -> None:
    res = run_in(cfg, work, ["/bin/sh", "-c", command])
    if res.returncode != 0:
        fail(f"{what}:\n{(res.stdout + res.stderr)[-3000:]}")


def for_relink(obj: bytes, fn: dict, known: set[str]) -> bytes:
    """A function's object as the relinked program takes it: what it reads and writes of its own statics is the
    game's (the address patched in, the relocation gone), its common symbols the game's globals of their names, and
    what else its file's C defines (a helper beside it) weak, so the program's own wins."""
    from elftools.elf.relocation import RelocationSection

    data = bytearray(obj)
    elf = ELFFile(BytesIO(obj))
    sections = list(elf.iter_sections())
    symtab = elf.get_section_by_name(".symtab")
    syms = list(symtab.iter_symbols())
    statics = fn.get("statics") or {}
    writable = {i for i, sec in enumerate(sections) if sec["sh_flags"] & SHF_WRITE and sec["sh_flags"] & 2}
    covering: dict[int, list] = {}
    for sym in syms:
        if sym["st_shndx"] in writable and sym["st_info"]["type"] == "STT_OBJECT" and sym.name in statics:
            covering.setdefault(sym["st_shndx"], []).append((sym["st_value"], max(sym["st_size"], 1), sym.name))

    def game_address(sym, addend: int) -> int | None:
        if sym["st_shndx"] not in writable:
            return None
        if sym["st_info"]["type"] == "STT_SECTION":
            for value, size, name in covering.get(sym["st_shndx"], ()):
                if value <= addend < value + size:
                    return statics[name] + addend - value
            return None
        return statics[sym.name] + addend if sym.name in statics else None

    shoff, entsz = elf["e_shoff"], elf["e_shentsize"]
    for i, rs in enumerate(sections):
        if not isinstance(rs, RelocationSection) or rs["sh_info"] in writable:
            continue
        target = sections[rs["sh_info"]]
        kept = []
        for r in rs.iter_relocations():
            at = target["sh_offset"] + r["r_offset"]
            addend = int.from_bytes(data[at:at + 4], "little", signed=True)
            sym = syms[r["r_info_sym"]]
            addr = game_address(sym, addend) if r["r_info_type"] == 1 else None
            if addr is None:
                kept.append((r["r_offset"], r["r_info"]))
            else:
                data[at:at + 4] = (addr & 0xFFFFFFFF).to_bytes(4, "little")
        for k, (off, info) in enumerate(kept):
            data[rs["sh_offset"] + k * 8:rs["sh_offset"] + k * 8 + 8] = off.to_bytes(4, "little") + info.to_bytes(4, "little")
        data[shoff + i * entsz + 20:shoff + i * entsz + 24] = (len(kept) * 8).to_bytes(4, "little")  # sh_size
    for k, sym in enumerate(syms):
        at = symtab["sh_offset"] + k * 16
        bind = sym["st_info"]["bind"]
        if sym["st_shndx"] == "SHN_COMMON" and sym.name in known:  # (a tentative definition: the game's global)
            data[at + 4:at + 12] = bytes(8)
            data[at + 14:at + 16] = SHN_UNDEF.to_bytes(2, "little")
        elif bind == "STB_GLOBAL" and sym.name != fn["name"] and isinstance(sym["st_shndx"], int) and sym["st_shndx"]:
            data[at + 12] = (2 << 4) | (data[at + 12] & 0xF)  # STB_WEAK
    return bytes(data)


DATA = (".rodata", ".data", ".bss")  # the program's data, written as data/program.s
LISTS = (".ctors", ".dtors", ".init_array", ".fini_array", ".preinit_array")  # what runs before and after main


def _data_source(game, starts: dict[int, str], imports: dict[int, str], asm: list[dict], labels: dict[int, list[str]],
                 own_lists: set[str]) -> tuple[str, int]:
    """The program's data as assembly that names what it points at: its globals labelled (`GameSettings:`), each word
    that pointed at a function, an import's PLT stub, or anywhere in its data written as that (`.long greet`,
    `.long __orig_rodata+0x1a4`), one into a function still in assembly (its switch's jump table) as that place in
    it; its constructor and destructor lists (a C++ program's globals, `__attribute__((constructor))`) by name,
    but for the functions whose C makes its own entry (`own_lists`). So the data can move with the code, and be
    changed. Returns the text and how many words still point into the old code (a C function's own old table)."""
    import bisect

    inner = sorted((f["vram"], f["vram"] + f["size"], f["name"]) for f in asm)
    lows = [lo_ for lo_, _, _ in inner]
    secs = {n: game.get_section_by_name(n) for n in DATA}
    spans = [(sec["sh_addr"], sec["sh_addr"] + sec["sh_size"], f"__orig_{n[1:]}") for n, sec in secs.items() if sec]
    text_sec = game.get_section_by_name(".text")
    lo, hi = text_sec["sh_addr"], text_sec["sh_addr"] + text_sec["sh_size"]

    def named(word: int) -> str | None:
        if word in starts:
            return starts[word]
        if word in imports:
            return imports[word]
        k = bisect.bisect_right(lows, word) - 1
        if k >= 0 and inner[k][0] < word < inner[k][1]:
            return f"{inner[k][2]}+{word - inner[k][0]}"
        if word in labels:
            return labels[word][0]
        for start, end, label in spans:
            if start <= word <= end:  # (one past the end too: a loop's limit)
                return f"{label}+{word - start}"
        return None

    out, stray = [], 0
    for name in DATA:
        sec = secs[name]
        if sec is None:
            continue
        addr, size = sec["sh_addr"], sec["sh_size"]
        nobits = sec["sh_type"] == "SHT_NOBITS"
        flags = '"aw",@nobits' if nobits else ('"a"' if name == ".rodata" else '"aw"')
        out.append(f".section .orig{name},{flags}\n.globl __orig_{name[1:]}\n__orig_{name[1:]}:\n")
        marks = sorted(a for a in labels if addr <= a < addr + size)
        raw = b"" if nobits else sec.data()
        i, run = 0, []

        def flush(run=run):
            if run:
                out.append(f".byte {','.join(map(str, run))}\n")
                run.clear()
        m = 0
        while i < size:
            while m < len(marks) and marks[m] - addr <= i:
                if marks[m] - addr == i:
                    flush()
                    out.append("".join(f".globl {n}\n{n}:\n" for n in labels[marks[m]]))
                m += 1
            if nobits:
                stop = (marks[m] - addr) if m < len(marks) else size
                out.append(f".skip {stop - i}\n")
                i = stop
                continue
            following = marks[m] - addr if m < len(marks) else size  # (a word may not run over a label)
            word = int.from_bytes(raw[i:i + 4], "little") if i + 4 <= min(size, following) and (addr + i) % 4 == 0 \
                else None
            target = named(word) if word is not None else None
            if target:
                flush()
                out.append(f".long {target}\n")
                i += 4
                continue
            if word is not None and lo <= word < hi:
                stray += 1
            run.append(raw[i])
            i += 1
            if len(run) == 32:
                flush()
        flush()
    for name in LISTS:  # (the original's entries, between crtbegin.o's start and crtend.o's end marker)
        sec = game.get_section_by_name(name)
        if sec is None or not sec["sh_size"]:
            continue
        words = [int.from_bytes(sec.data()[k:k + 4], "little") for k in range(0, sec["sh_size"] - 3, 4)]
        entries = [w for w in words if w not in (0, 0xFFFFFFFF) and starts.get(w) not in own_lists]
        if entries:
            out.append(f'.section {name},"aw"\n' + "".join(f".long {named(w) or hex(w)}\n" for w in entries))
    return "".join(out), stray


def _translate(program: Path, old: dict[str, tuple[int, int]]) -> int:
    """The relinked program's code with the old data addresses its C still writes as numbers (and its statics,
    patched as the game's) moved with the data: every absolute operand in a data section's old span becomes the same
    place in the section where it is now. Returns how many."""
    import capstone

    data = bytearray(program.read_bytes())
    elf = ELFFile(BytesIO(bytes(data)))
    symtab = elf.get_section_by_name(".symtab")
    now = {s.name: s["st_value"] for s in symtab.iter_symbols() if s.name.startswith("__orig_")}
    moves = [(start, end, now[label] - start) for label, (start, end) in old.items() if label in now
             and now[label] != start]
    if not moves:
        return 0
    text = elf.get_section_by_name(".text")
    base, off = text["sh_addr"], text["sh_offset"]
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    md.skipdata = True
    done = 0
    for ins in md.disasm(bytes(text.data()), base):
        if ins.id == 0:
            continue
        for field, value in ((ins.imm_offset, next((o.imm for o in ins.operands if o.type == capstone.x86.X86_OP_IMM), None)),
                             (ins.disp_offset, next((o.mem.disp for o in ins.operands if o.type == capstone.x86.X86_OP_MEM
                                                     and o.mem.base == 0), None))):
            if not field or value is None or ins.size - field < 4:
                continue
            value &= 0xFFFFFFFF
            for start, end, delta in moves:
                if start <= value <= end:
                    at = off + ins.address - base + field
                    data[at:at + 4] = ((value + delta) & 0xFFFFFFFF).to_bytes(4, "little")
                    done += 1
                    break
    program.write_bytes(bytes(data))
    return done


def _link_stubs(game, cc_cfg, work: Path, tc: Path) -> list[str]:
    """Shared libraries to link against, one per library the program needs, holding what it imports from each at
    the versions it asked for (objects with their sizes, for the copies the linker makes): the run uses the real
    ones. (A newer glibc's IFUNCs are data to a 2001 linker: memset was copied into .bss.)"""
    from elftools.elf.dynamic import DynamicSection
    from elftools.elf.gnuversions import GNUVerNeedSection, GNUVerSymSection

    dynsym = game.get_section_by_name(".dynsym")
    need = next((s for s in game.iter_sections() if isinstance(s, GNUVerNeedSection)), None)
    versym = next((s for s in game.iter_sections() if isinstance(s, GNUVerSymSection)), None)
    needed = [t.needed for s in game.iter_sections() if isinstance(s, DynamicSection)
              for t in s.iter_tags() if t.entry.d_tag == "DT_NEEDED"]
    index = {}
    for vn, auxs in (need.iter_versions() if need is not None else ()):
        for aux in auxs:
            index[aux["vna_other"]] = (vn.name, aux.name)
    libs: dict[str, dict[str, list]] = {lib: {} for lib in needed}
    plain = next((lib for lib in needed if lib not in {v[0] for v in index.values()}), needed[0] if needed else None)
    for k, sym in enumerate(dynsym.iter_symbols()):
        if not sym.name or sym["st_shndx"] != "SHN_UNDEF" or sym["st_info"]["bind"] == "STB_WEAK":
            continue
        lib, ver = index.get(versym.get_symbol(k)["ndx"] if versym is not None else 0, (plain, None))
        libs.setdefault(lib, {}).setdefault(ver, []).append(sym)
    made = []
    for lib in needed:
        source, script, prev = [], [], None
        for ver, syms in sorted(libs.get(lib, {}).items(), key=lambda kv: (kv[0] is not None, kv[0] or "")):
            for sym in syms:
                source.append(f"char {sym.name}[{max(sym['st_size'], 1)}] = {{ 1 }};"
                              if sym["st_info"]["type"] == "STT_OBJECT" else f"int {sym.name}() {{ return 0; }}")
            if ver is not None:
                names = "; ".join(sym.name for sym in syms)
                script.append(f"{ver} {{ global: {names}; }}{(' ' + prev) if prev else ''};")
                prev = ver
        stem = re.sub(r"\W", "_", lib)
        res = compile_source(cc_cfg, "", "\n".join(source) + "\nint __decompdecomp_stub;\n", trusted=True)
        if not res.ok:
            fail(f"a stub of {lib} doesn't compile:\n{res.log[-2000:]}")
        (work / f"{stem}.o").write_bytes(res.obj)
        version = f"--version-script {stem}.map " if script else ""
        (work / f"{stem}.map").write_text("\n".join(script) + "\n", encoding="utf-8")
        _run(cc_cfg, work, f"{_tool(tc, 'ld')} -m elf_i386 -shared -soname {lib} {version}-o {lib} {stem}.o",
             f"a stub of {lib} doesn't link")
        made.append(lib)
    return made


def relink(move: bool = False) -> Path:
    """build/<program>: a new program from the C (see above). `move`: its data laid out after the code too, not
    where the game has it (python build.py relink --move)."""
    data = original()
    game = ELFFile(BytesIO(data))
    tcid = B.get("toolchain") or "gcc-2.95.3-linux"
    tc = Path(toolchains.ensure(tcid, log=lambda *_: None))
    crt = tc / "crt"
    begin = next(iter(sorted(tc.glob("gcc/usr/lib/**/crtbegin.o"))), None)
    if game.get_section_by_name(".interp") is not None and (not (crt / "crt1.o").exists() or begin is None):
        fail(f"{tcid} has no C runtime objects to link a program with: update decompdecomp")
    work = ROOT / "build" / "relink"
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    cc_cfg = compiler_config(work, {"compiler": {"toolchain": tcid, "flags": ["-O0", "-fPIC"]}})
    starts = {f["vram"]: f["name"] for f in B["functions"]}
    names = set(starts.values())
    dynsym = game.get_section_by_name(".dynsym")
    dynamic = game.get_section_by_name(".interp") is not None
    imported = {s.name for s in dynsym.iter_symbols() if s.name and s["st_shndx"] == "SHN_UNDEF"} if dynsym else set()
    if not dynamic:  # (a static program: all of its code is its functions, crt and library ones too)
        if starts.get(game["e_entry"]) is None:
            fail(f"the program starts at 0x{game['e_entry']:X}, where none of its functions is")
        for name in (".init", ".fini", *LISTS):
            if (sec := game.get_section_by_name(name)) is not None and sec["sh_size"] > 8:
                fail(f"a static program's {name} can't be relinked yet")
    objs, from_c, own_lists = [], 0, set()
    for fn in B["functions"]:
        src = source_of(fn)
        if src is not None:
            res = compile_source(config(fn, work, placed=False), "", src.read_text(encoding="utf-8"), trusted=True)
            if not res.ok:
                fail(f"{src.relative_to(ROOT)} doesn't compile:\n{res.log[-3000:]}")
            (work / f"{fn['name']}.o").write_bytes(for_relink(res.obj, fn, set(B["symbols"])))
            if any(ELFFile(BytesIO(res.obj)).get_section_by_name(n) is not None for n in LISTS):
                own_lists.add(fn["name"])  # (its C makes its own constructor entry)
            from_c += 1
        else:
            asm = ROOT / (fn.get("s") or f"asm/{fn['name']}.s")
            if not asm.exists():
                fail(f"{fn['name']} is neither C nor assembly (asm/{fn['name']}.s): export again")
            shutil.copyfile(asm, work / f"{fn['name']}.s")
            _run(cc_cfg, work, f"{_tool(tc, 'as')} -o {fn['name']}.o {fn['name']}.s", f"asm/{fn['name']}.s doesn't assemble")
        objs.append(f"{fn['name']}.o")
    plt = _plt(game)
    libs = _link_stubs(game, cc_cfg, work, tc) if dynamic else []
    runtime = [crt / "crt1.o", crt / "crti.o", begin] if dynamic else []
    ending = [begin.with_name("crtend.o"), crt / "crtn.o"] if dynamic else []
    defined = set()
    for f in runtime + ending:
        defined |= {s.name for s in ELFFile(BytesIO(f.read_bytes())).get_section_by_name(".symtab").iter_symbols()
                    if s.name and s["st_shndx"] != "SHN_UNDEF"}
    ro, da, bss = (game.get_section_by_name(n) for n in DATA)
    spans = {f"__orig_{n[1:]}": (sec["sh_addr"], sec["sh_addr"] + sec["sh_size"]) for n, sec in zip(DATA, (ro, da, bss))
             if sec is not None}
    assigns, labels = [], {}
    for name, addr in sorted(B["symbols"].items(), key=lambda kv: kv[1]):
        if name in names or name in imported or name in defined:
            continue
        if addr in starts:
            assigns.append(f"{name} = {starts[addr]};")
        elif any(start <= addr < end for start, end in spans.values()):
            labels.setdefault(addr, []).append(name)  # (a label in data/program.s: it moves with the data)
        else:
            assigns.append(f"{name} = 0x{addr:X};")
    # the program's data as a source file: written from your copy the first time, then yours to change
    source = ROOT / "data" / "program.s"
    if not source.exists():
        text, stray = _data_source(game, starts, {addr: name for name, addr in plt.items()},
                                   [f for f in B["functions"] if source_of(f) is None], labels, own_lists)
        source.parent.mkdir(exist_ok=True)
        source.write_text(text, encoding="utf-8")
        note = f"; {stray} words still point into the old code, at C functions' own old tables" if stray else ""
        print(f"data/program.s: the program's data, written from your copy ({sum(map(len, labels.values()))} globals "
              f"named{note})")
    shutil.copyfile(source, work / "data.s")
    _run(cc_cfg, work, f"{_tool(tc, 'as')} -o data.o data.s", "data/program.s doesn't assemble")
    end = max(s["sh_addr"] + s["sh_size"] for s in (ro, da, bss) if s is not None)
    code = (end + 0xFFFFF) & ~0xFFFFF  # (above the game's data: the code may grow)
    # (a static program has no dynamic sections for the headers' segment: its read-only data goes there instead)
    pinned = "" if move else "".join(f"  .orig{n} 0x{s['sh_addr']:X} : {{ data.o(.orig{n}) }} :{seg}\n"
                                     for n, s, seg in ((".rodata", ro, "rodata" if dynamic else "text"),
                                                       (".data", da, "data"), (".bss", bss, "data"))
                                     if s is not None)
    moved = {n: f"  .orig{n} : {{ data.o(.orig{n}) }}\n" if move else "" for n in DATA}
    entry = "_start" if dynamic else starts[game["e_entry"]]
    # (crtbegin.o's list start first, crtend.o's end marker last)
    ctors = "".join(f"  .{k} : {{ KEEP ({begin}(.{k})) KEEP (*(EXCLUDE_FILE ({ending[0]}) .{k})) KEEP (*(.{k})) }}\n"
                    for k in ("ctors", "dtors")) if dynamic else ""
    script = f"""OUTPUT_FORMAT("elf32-i386")
OUTPUT_ARCH(i386)
ENTRY({entry})
PHDRS
{{
""" + ("""  headers PT_PHDR PHDRS ;
  interp PT_INTERP ;
""" if dynamic else "") + """  text PT_LOAD FILEHDR PHDRS ;
""" + ("  rodata PT_LOAD ;\n" if dynamic and not move else "") + ("  data PT_LOAD ;\n" if not move else "") + """  code PT_LOAD ;
  more PT_LOAD ;
""" + ("  dynamic PT_DYNAMIC ;\n" if dynamic else "") + f"""}}
SECTIONS
{{
  . = 0x{min(s_["sh_addr"] for s_ in game.iter_sections() if s_["sh_addr"]) & ~0xFFF:X} + SIZEOF_HEADERS;
  .interp : {{ *(.interp) }} :text {":interp" if dynamic else ""}
  .hash : {{ *(.hash) }} :text
  .dynsym : {{ *(.dynsym) }}
  .dynstr : {{ *(.dynstr) }}
  .gnu.version : {{ *(.gnu.version) }}
  .gnu.version_d : {{ *(.gnu.version_d) }}
  .gnu.version_r : {{ *(.gnu.version_r) }}
  .rel.dyn : {{ *(.rel.init) *(.rel.text) *(.rel.fini) *(.rel.rodata) *(.rel.data) *(.rel.ctors) *(.rel.dtors) *(.rel.got) *(.rel.bss) }}
  .rel.plt : {{ *(.rel.plt) }}
{pinned}  . = 0x{code:X};
  .init : {{ KEEP (*(.init)) }} :code =0x9090
  .plt : {{ *(.plt) }}
  .text : {{ *(.text) *(.text.*) *(.gnu.linkonce.t.*) }} =0x9090
  .fini : {{ KEEP (*(.fini)) }} =0x9090
  .rodata : {{ *(.rodata) *(.rodata.*) *(.gnu.linkonce.r.*) }}
{moved[".rodata"]}  .gcc_except_table : {{ *(.gcc_except_table) }}
  . = ALIGN(0x1000) + (. & 0xFFF);
  .data : {{ *(.data) *(.data.*) *(.gnu.linkonce.d.*) }} :more
{moved[".data"]}  .eh_frame : {{ KEEP (*(.eh_frame)) }}
{ctors}  .preinit_array : {{ PROVIDE (__preinit_array_start = .); KEEP (*(.preinit_array)) PROVIDE (__preinit_array_end = .); }}
  .init_array : {{ PROVIDE (__init_array_start = .); KEEP (*(.init_array)) PROVIDE (__init_array_end = .); }}
  .fini_array : {{ PROVIDE (__fini_array_start = .); KEEP (*(.fini_array)) PROVIDE (__fini_array_end = .); }}
  .jcr : {{ KEEP (*(.jcr)) }}
  .got : {{ *(.got.plt) *(.got) }}
  .dynamic : {{ *(.dynamic) }} :more {":dynamic" if dynamic else ""}
  _edata = .;
  __bss_start = .;
  .bss : {{ *(.dynbss) *(.bss) *(.bss.*) *(.gnu.linkonce.b.*) *(COMMON) . = ALIGN(4); }} :more
{moved[".bss"]}  _end = .;
  /DISCARD/ : {{ *(.comment) *(.note*) *(.stab*) }}
}}
""" + "\n".join(assigns) + "\n"
    (work / "program.ld").write_text(script, encoding="utf-8")
    (work / "objects.txt").write_text("\n".join(objs) + "\n", encoding="utf-8")
    libgcc = begin.with_name("libgcc.a") if begin is not None else Path("-")
    out = B.get("program") or "program.relinked"
    if dynamic:
        link = (f"{_tool(tc, 'ld')} -m elf_i386 -dynamic-linker /lib/ld-linux.so.2 -rpath-link . -T program.ld "
                f"-o {out} {runtime[0]} {runtime[1]} {runtime[2]} $(cat objects.txt) data.o {crt / 'libc_nonshared.a'} "
                f"{' '.join(libs)} {libgcc if libgcc.exists() else ''} {ending[0]} {ending[1]}")
    else:
        link = f"{_tool(tc, 'ld')} -m elf_i386 -static -T program.ld -o {out} $(cat objects.txt) data.o"
    _run(cc_cfg, work, link, "the program doesn't link")
    final = ROOT / "build" / out
    shutil.copyfile(work / out, final)
    final.chmod(0o755)
    shifted = _translate(final, spans) if move else 0
    print(f"build/{out}: relinked, a new program from the C ({from_c} of {len(B['functions'])} functions from C, the "
          f"rest from asm/; the data from data/program.s, "
          + (f"laid out after the code: {shifted} addresses the C still wrote as the old data's moved with it)"
             if move else "where the game has it)"))
    return final


def _plt(game) -> dict[str, int]:
    """Each import's PLT stub in the original: the n-th R_386_JUMP_SLOT is the n-th entry after PLT0."""
    rel, plt = game.get_section_by_name(".rel.plt"), game.get_section_by_name(".plt")
    if rel is None or plt is None:
        return {}
    syms = game.get_section(rel["sh_link"])
    return {syms.get_symbol(r["r_info_sym"]).name.split("@")[0]: plt["sh_addr"] + 16 * (n + 1)
            for n, r in enumerate(rel.iter_relocations())}


